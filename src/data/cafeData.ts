// Helper to check if cafe is currently open
export function isCafeCurrentlyOpen(): { isOpen: boolean; statusText: string; timeDetails: string } {
  // Opening hours: 12:30 PM (12.5) to 10:30 PM (22.5)
  const now = new Date();
  const currentHour = now.getHours();
  const currentMinute = now.getMinutes();
  const currentTimeVal = currentHour + currentMinute / 60;

  const openTimeVal = 12 + 30 / 60; // 12:30
  const closeTimeVal = 22 + 30 / 60; // 22:30

  const isOpen = currentTimeVal >= openTimeVal && currentTimeVal < closeTimeVal;
  
  if (isOpen) {
    return {
      isOpen: true,
      statusText: 'Open Now',
      timeDetails: 'Open today until 10:30 PM',
    };
  } else {
    return {
      isOpen: false,
      statusText: 'Opens at 12:30 PM',
      timeDetails: 'Daily 12:30 PM – 10:30 PM',
    };
  }
}
